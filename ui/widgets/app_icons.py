def svg_pixmap(name: str, color: str = "#1e293b", size: int = 18) -> QPixmap:
    """Renderiza un icono SVG vectorial en un QPixmap nítido."""
    body = _SVG_PATHS.get(name, _SVG_PATHS["file-text"])
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" '
        f'stroke-width="1.85" stroke-linecap="round" stroke-linejoin="round">'
        f"{body}</svg>"
    ).encode("utf-8")
    renderer = QSvgRenderer(svg)
    pix = QPixmap(QSize(size, size))
    pix.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pix)
    renderer.render(painter)
    painter.end()
    return pix


def svg_icon(name: str, color: str = "#1e293b", size: int = 18) -> QIcon:
    """Devuelve un QIcon vectorial para botones y menús."""
    return QIcon(svg_pixmap(name, color=color, size=size))
